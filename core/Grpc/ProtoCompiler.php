<?php

namespace Ryra\Core\Grpc;

use Google\Protobuf\DescriptorPool;
use Google\Protobuf\Internal\Message as NativeMessage;
use Ryra\Core\Grpc\Metadata\MetadataFactory;
use Ryra\Core\Grpc\Metadata\ServiceMetadata;
use RuntimeException;

/**
 * Build nội bộ cho google/protobuf:
 *  1. Sinh .proto từ class #[Service] / #[Message] (kèm php_namespace riêng).
 *  2. Gọi protoc --php_out để sinh class Google.
 *  3. Biên dịch thêm các file .proto có sẵn (proto-first) nếu được cấu hình.
 *  4. Ghi class map DTO => class protoc để Codec dùng lúc chạy.
 */
final class ProtoCompiler
{
    public const CLASS_MAP = 'classmap.php';

    /**
     * @param string $buildPath Thư mục build (vd storage/grpc).
     * @param string $namespace Namespace gốc cho class protoc sinh từ DTO.
     * @param string[] $protoPaths Thư mục chứa .proto có sẵn cần biên dịch thêm.
     * @param string[] $includePaths Thư mục include thêm cho protoc.
     */
    public function __construct(
        private readonly string $buildPath,
        private readonly string $namespace = 'GrpcStub',
        private readonly string $protoc = 'protoc',
        private readonly array $protoPaths = [],
        private readonly array $includePaths = [],
    ) {}

    public function phpPath(): string
    {
        return $this->buildPath . '/php';
    }

    public function classMapPath(): string
    {
        return $this->buildPath . '/' . self::CLASS_MAP;
    }

    /**
     * Đăng ký autoload cho thư mục chứa class protoc sinh ra (namespace <=> thư mục).
     */
    public static function registerAutoloader(string $phpPath): void
    {
        \spl_autoload_register(static function (string $class) use ($phpPath): void {
            $file = $phpPath . '/' . \str_replace('\\', '/', $class) . '.php';
            if (\is_file($file)) {
                require_once $file;
            }
        });
    }

    /**
     * @param ServiceMetadata[] $services
     * @param string[] $messages
     * @return array{proto: string[], classes: int} Danh sách file .proto đã biên dịch và số class được map.
     */
    public function compile(array $services, array $messages = []): array
    {
        $this->ensureProtoc();

        $protoDir = $this->buildPath . '/proto';
        $phpDir = $this->phpPath();
        self::cleanDirectory($protoDir);
        self::cleanDirectory($phpDir);

        $generator = new ProtoGenerator(phpNamespace: $this->namespace);
        $files = $generator->generate($services, $messages);
        foreach ($files as $name => $content) {
            \file_put_contents("$protoDir/$name", $content);
        }

        $compiled = [];
        if ($files !== []) {
            $this->runProtoc([$protoDir, ...$this->includePaths], \array_map(fn ($name) => "$protoDir/$name", \array_keys($files)), $phpDir);
            $compiled = \array_keys($files);
        }

        foreach ($this->protoPaths as $path) {
            $protoFiles = self::findProtoFiles($path);
            if ($protoFiles !== []) {
                $this->runProtoc([$path, ...$this->includePaths], $protoFiles, $phpDir);
                $compiled = [...$compiled, ...$protoFiles];
            }
        }

        $classMap = $this->buildClassMap($generator);
        \file_put_contents(
            $this->classMapPath(),
            "<?php\n\n// Generated by `php ryra grpc:generate`. DO NOT EDIT.\nreturn " . \var_export($classMap, true) . ";\n"
        );

        return ['proto' => $compiled, 'classes' => \count($classMap)];
    }

    private function buildClassMap(ProtoGenerator $generator): array
    {
        self::registerAutoloader($this->phpPath());

        // proto full name => class protoc
        $natives = [];
        $pool = DescriptorPool::getGeneratedPool();
        foreach (self::findPhpClasses($this->phpPath()) as $class) {
            if (!\class_exists($class) || !\is_subclass_of($class, NativeMessage::class)) {
                continue;
            }
            new $class(); // nạp descriptor vào pool
            $natives[$pool->getDescriptorByClassName($class)->getFullName()] = $class;
        }

        $map = [];
        foreach ($generator->messagePackages() as $class => $package) {
            $metadata = MetadataFactory::forMessage($class);
            if ($metadata->wellKnown !== null) {
                continue;
            }
            $fullName = ($package === '' ? '' : "$package.") . $metadata->name;
            $map[$class] = $natives[$fullName]
                ?? throw new RuntimeException("protoc did not generate a class for [$fullName]");
        }
        \ksort($map);

        return $map;
    }

    private function runProtoc(array $includes, array $files, string $outDir): void
    {
        $command = [$this->protoc];
        foreach (\array_unique($includes) as $include) {
            $command[] = '--proto_path=' . $include;
        }
        $command[] = '--php_out=' . $outDir;
        $command = [...$command, ...$files];

        $process = \proc_open($command, [1 => ['pipe', 'w'], 2 => ['pipe', 'w']], $pipes);
        if (!\is_resource($process)) {
            throw new RuntimeException('Cannot start protoc');
        }
        $stdout = \stream_get_contents($pipes[1]);
        $stderr = \stream_get_contents($pipes[2]);
        \fclose($pipes[1]);
        \fclose($pipes[2]);

        if (\proc_close($process) !== 0) {
            throw new RuntimeException("protoc failed:\n" . \trim($stderr . "\n" . $stdout));
        }
    }

    private function ensureProtoc(): void
    {
        \exec(\escapeshellarg($this->protoc) . ' --version 2>&1', $output, $code);
        if ($code !== 0) {
            throw new RuntimeException(
                "protoc not found ({$this->protoc}). Install it: `brew install protobuf` (macOS) "
                . 'or `apt-get install -y protobuf-compiler` (Debian/Ubuntu), or set GRPC_PROTOC.'
            );
        }
    }

    /**
     * @return string[]
     */
    public static function findProtoFiles(string $path): array
    {
        if (!\is_dir($path)) {
            return [];
        }
        $files = [];
        $iterator = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($path, \FilesystemIterator::SKIP_DOTS));
        foreach ($iterator as $file) {
            if ($file->getExtension() === 'proto') {
                $files[] = $file->getPathname();
            }
        }
        \sort($files);
        return $files;
    }

    /**
     * @return string[]
     */
    private static function findPhpClasses(string $path): array
    {
        if (!\is_dir($path)) {
            return [];
        }
        $classes = [];
        $iterator = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($path, \FilesystemIterator::SKIP_DOTS));
        foreach ($iterator as $file) {
            if ($file->getExtension() === 'php') {
                $relative = \substr($file->getPathname(), \strlen($path) + 1, -4);
                $classes[] = \str_replace('/', '\\', $relative);
            }
        }
        \sort($classes);
        return $classes;
    }

    private static function cleanDirectory(string $path): void
    {
        if (\is_dir($path)) {
            $iterator = new \RecursiveIteratorIterator(
                new \RecursiveDirectoryIterator($path, \FilesystemIterator::SKIP_DOTS),
                \RecursiveIteratorIterator::CHILD_FIRST
            );
            foreach ($iterator as $file) {
                $file->isDir() ? \rmdir($file->getPathname()) : \unlink($file->getPathname());
            }
        } else {
            \mkdir($path, 0775, true);
        }
    }
}
